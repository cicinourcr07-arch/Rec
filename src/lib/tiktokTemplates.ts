export async function listTikTokTemplates(): Promise<TikTokTemplateDefinition[]> {
  const custom = (await indexedDbStore.getKv<TikTokTemplateDefinition[]>(CUSTOM_TEMPLATES_KV)) || [];
  return [...custom, ...BUILTIN_TIKTOK_TEMPLATES];
}

export async function saveCustomTikTokTemplate(def: TikTokTemplateDefinition): Promise<TikTokTemplateDefinition[]> {
  const current = (await indexedDbStore.getKv<TikTokTemplateDefinition[]>(CUSTOM_TEMPLATES_KV)) || [];
  const next = [def, ...current.filter((t) => t.id !== def.id)];
  await indexedDbStore.setKv(CUSTOM_TEMPLATES_KV, next);
  return [...next, ...BUILTIN_TIKTOK_TEMPLATES];
}

export async function deleteCustomTikTokTemplate(id: string): Promise<TikTokTemplateDefinition[]> {
  const current = (await indexedDbStore.getKv<TikTokTemplateDefinition[]>(CUSTOM_TEMPLATES_KV)) || [];
  const next = current.filter((t) => t.id !== id);
  await indexedDbStore.setKv(CUSTOM_TEMPLATES_KV, next);
  return [...next, ...BUILTIN_TIKTOK_TEMPLATES];
}

export async function getFavoriteTikTokTemplateIds(): Promise<string[]> {
  return (await indexedDbStore.getKv<string[]>(TEMPLATE_FAVS_KV)) || [];
}

export async function toggleFavoriteTikTokTemplate(id: string): Promise<string[]> {
  const favs = await getFavoriteTikTokTemplateIds();
  const next = favs.includes(id) ? favs.filter((f) => f !== id) : [...favs, id];
  await indexedDbStore.setKv(TEMPLATE_FAVS_KV, next);
  return next;
}

export function applyTikTokTemplateToProject(
  project: Project,
  template: TikTokTemplateDefinition
): Project {
  return {
    ...project,
    subtitleStyle: {
      ...project.subtitleStyle,
      ...template.subtitleStyle,
      enabled: project.subtitleStyle.enabled, // preserve user preview toggle
      useTranslated: true,
    },
    videoEffects: {
      ...project.videoEffects,
      ...(template.videoEffects || {}),
      filterPreset: template.videoEffects.filterPreset || project.videoEffects.filterPreset,
    },
  };
}
